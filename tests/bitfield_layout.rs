fn manifest_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn corpus_path() -> PathBuf {
    manifest_dir().join("tests/include/bitfields_corpus.h")
}

fn checks_path() -> PathBuf {
    manifest_dir().join("tests/include/bitfields_corpus_checks.rs")
}

/// The compiler to compare against, if there is one.
fn c_compiler() -> Option<String> {
    let named = std::env::var("CINRS_BITFIELD_CC")
        .or_else(|_| std::env::var("CC"))
        .unwrap_or_else(|_| "cc".to_owned());
    let ok = Command::new(&named)
        .arg("--version")
        .output()
        .is_ok_and(|out| out.status.success());
    ok.then_some(named)
}

#[test]
fn the_committed_corpus_is_what_the_generator_produces() {
    let generated = corpus();
    let files = [
        (corpus_path(), generated.header),
        (checks_path(), generated.checks),
    ];
    let bless = std::env::var_os("CINRS_BLESS_BITFIELD_CORPUS").is_some();
    for (path, wanted) in files {
        if bless {
            std::fs::write(&path, &wanted).expect("the corpus directory must be writable");
            continue;
        }
        let on_disk = std::fs::read_to_string(&path).expect("the corpus must be checked in");
        assert!(
            on_disk == wanted,
            "{} is not what the generator in this file produces; regenerate it with\n    \
             CINRS_BLESS_BITFIELD_CORPUS=1 cargo test --test bitfield_layout",
            path.display()
        );
    }
}

/// The size and alignment `cinrs` folded into the generated code have to be
/// the ones `rustc` gave the items it generated, or `sizeof` inside the C is a
/// different number from the object the C runs on.
#[test]
fn the_layout_cinrs_computed_is_the_one_rustc_gave() {
    check_generated_layout();
}

/// One record: what the C thinks its size and alignment are against what the
/// Rust item really has.
fn check_record<T>(index: usize, name: &str) {
    let index = index as ::core::ffi::c_int;
    let null = ::core::ptr::null_mut();
    let size = unsafe { bf_query(index, 0, 0, 0, null) };
    let align = unsafe { bf_query(index, 1, 0, 0, null) };
    assert_eq!(size as usize, size_of::<T>(), "sizeof {name}");
    assert_eq!(align as usize, align_of::<T>(), "_Alignof {name}");
}

/// The same, for a record whose Rust item cannot carry the alignment.
///
/// One member packed and the rest not is the only shape where the two differ:
/// Rust refuses `#[repr(C, packed, align(N))]`, so the item is one byte
/// aligned. What the C program can observe — every offset, and `sizeof` — is
/// still identical, and the alignment the item does have must at least divide
/// the one C computed, or an array of them would stride differently.
fn check_record_size_only<T>(index: usize, name: &str) {
    let index = index as ::core::ffi::c_int;
    let null = ::core::ptr::null_mut();
    let size = unsafe { bf_query(index, 0, 0, 0, null) };
    let align = unsafe { bf_query(index, 1, 0, 0, null) };
    assert_eq!(size as usize, size_of::<T>(), "sizeof {name}");
    assert!(
        (align as usize).is_multiple_of(align_of::<T>()),
        "_Alignof {name}: the item's {} does not divide C's {align}",
        align_of::<T>()
    );
}

/// One ordinary member: `offsetof` against `offset_of!`.
fn check_offset(index: usize, member: usize, actual: usize, name: &str) {
    let null = ::core::ptr::null_mut();
    let want = unsafe {
        bf_query(
            index as ::core::ffi::c_int,
            3,
            member as ::core::ffi::c_int,
            0,
            null,
        )
    };
    assert_eq!(want as usize, actual, "offsetof {name}");
}

#[test]
fn the_layout_agrees_with_the_host_c_compiler() {
    let Some(cc) = c_compiler() else {
        println!(
            "skipping: no C compiler on PATH (set CINRS_BITFIELD_CC or CC to name one), \
             so there is nothing to compare the bit-field layout against"
        );
        return;
    };

    let ours = report_through_cinrs();
    let theirs = report_through(&cc);
    if ours == theirs {
        return;
    }
    let mismatch = ours
        .lines()
        .zip(theirs.lines())
        .find(|(a, b)| a != b)
        .map(|(a, b)| format!("cinrs: {a}\n   {cc}: {b}"))
        .unwrap_or_else(|| {
            format!(
                "the reports have different lengths: {} lines from cinrs, {} from {cc}",
                ours.lines().count(),
                theirs.lines().count()
            )
        });
    panic!("the bit-field layout differs from {cc}'s:\n{mismatch}");
}

/// The report as the translated corpus produces it.
fn report_through_cinrs() -> String {
    // Large enough for the whole corpus; the C side uses the same bound.
    let mut buffer = vec![0u8; 1 << 23];
    let written = unsafe { bf_report(buffer.as_mut_ptr().cast()) };
    let len = usize::try_from(written).expect("the report cannot be negative");
    assert!(len < buffer.len(), "the report buffer was too small");
    String::from_utf8(buffer[..len].to_vec()).expect("the report is ASCII")
}

/// The report as the host compiler produces it.
fn report_through(cc: &str) -> String {
    let dir = manifest_dir().join("target/bitfield-layout");
    std::fs::create_dir_all(&dir).expect("target/ must be writable");
    let source = dir.join("main.c");
    std::fs::write(&source, MAIN_C).expect("target/ must be writable");
    let binary = dir.join("corpus_report");

    let include = corpus_path()
        .parent()
        .expect("the corpus has a directory")
        .to_path_buf();
    let output = Command::new(cc)
        .args(["-std=c11", "-w", "-O0"])
        .arg("-I")
        .arg(&include)
        .arg(&source)
        .arg("-o")
        .arg(&binary)
        .output()
        .unwrap_or_else(|e| panic!("could not run {cc}: {e}"));
    assert!(
        output.status.success(),
        "{cc} could not compile the corpus:\n{}",
        String::from_utf8_lossy(&output.stderr)
    );
    run(&binary)
}

fn run(binary: &Path) -> String {
    let output = Command::new(binary)
        .output()
        .unwrap_or_else(|e| panic!("could not run {}: {e}", binary.display()));
    assert!(
        output.status.success(),
        "{} exited with {}",
        binary.display(),
        output.status
    );
    String::from_utf8(output.stdout).expect("the report is ASCII")
}
